"""2.1.0 (#226): Python dependencies are compiled with pip-tools (requirements.in -> requirements.txt).

Offline checks (the re-compile itself needs the package index): requirements.txt is pip-compile output for
requirements.in with Python 3.12, every direct pin of requirements.in is in requirements.txt at the same version,
every line of requirements.txt is an exact pin, and Dependabot no longer holds pydantic back.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BACKEND = ROOT / "backend"


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _pins(path: Path) -> dict[str, str]:
    out = {}
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        m = re.fullmatch(r"([A-Za-z0-9_.-]+)==([A-Za-z0-9_.+!-]+)", line)
        assert m, f"{path.name}: not an exact pin: {line!r}"
        out[_norm(m.group(1))] = m.group(2)
    return out


def test_requirements_txt_is_compiled_from_requirements_in():
    text = (BACKEND / "requirements.txt").read_text()
    assert "autogenerated by pip-compile with Python 3.12" in text
    assert "pip-compile --no-emit-index-url --strip-extras requirements.in" in text


def test_direct_pins_match():
    direct = _pins(BACKEND / "requirements.in")
    full = _pins(BACKEND / "requirements.txt")
    for name, ver in direct.items():
        assert full.get(name) == ver, f"{name}: requirements.in {ver}, requirements.txt {full.get(name)} - re-compile"
    # the packages PennyWarden imports itself are direct dependencies
    for name in ("fastapi", "starlette", "pydantic", "uvicorn", "sqlalchemy", "alembic", "argon2-cffi", "cryptography",
                 "python-multipart", "pillow", "reportlab", "pypdf", "pyotp", "segno", "google-re2", "pypdfium2"):
        assert name in direct, name
    # pydantic_core comes from pydantic's own requirement, so they always move together
    assert "pydantic-core" not in direct and "pydantic-core" in full


def test_every_compiled_entry_is_annotated():
    lines = (BACKEND / "requirements.txt").read_text().splitlines()
    for i, line in enumerate(lines):
        if re.match(r"^[A-Za-z0-9_.-]+==", line):
            assert lines[i + 1].lstrip().startswith("# via"), line


def test_dependabot_no_longer_holds_pydantic_back():
    text = (ROOT / ".github" / "dependabot.yml").read_text()
    assert 'dependency-name: "pydantic' not in text
    assert "directory: /backend" in text
